"""Переносы стандартных предложений из макета Special Offers."""
from django import template

register = template.Library()

TITLES = {
    'Тариф "День рождения"': 'Тариф\n”День рождения”',
    'Тариф "Пятница со скидкой 50%"': 'Тариф ”Пятница\nсо скидкой 50%”',
    'Тариф "С мая по сентябрь"': 'Тариф\n”С мая по сентябрь”',
    'Тариф "Выгодная баня"': 'Тариф\n”Выгодная баня”',
    'Тариф "Гостеприимство"': 'Тариф\n”Гостеприимство”',
    'Тариф "Правильная удаленка"': 'Тариф\n”Правильная удаленка”',
    'Тариф "С октября по апрель"': 'Тариф\n”С октября по апрель”',
}
DESCRIPTIONS = [
    'Дарим скидку в день рождения - 15%',
    'При бронировании 3-х дней:\nпятницы, субботы и воскресения,\nна пятницу действует скидка 50%',
    'От 3-х суток скидка 10%\nОт 5 суток - 15%\nОт 7 суток - 20%',
    'При бронировании русской бани\nот 3-х часов - баня рассчитывается\nпо тарифу 1 500Р/час',
    'При бронировании напрямую\nкомплимент от хозяев: набор\nфермерских продуктов или\nдополнительный час в бане',
    '4 дня по цене 3 в будние дни',
    'От 3-х суток скидка 10%\nОт 5 суток - 20%\nОт 7 суток - 25%',
]


@register.filter
def promotion_title(value):
    return TITLES.get(value.replace('«', '"').replace('»', '"'), value)


@register.filter
def promotion_description(value):
    for text in DESCRIPTIONS:
        if ' '.join(value.split()) == ' '.join(text.split()):
            return text
    return value
