def _now_block():
    from django.utils import timezone

    from core import dop_content as dc

    month = timezone.localdate().month
    in_season = [title for title, detail in dc.ACTIVITY_DETAILS.items() if month in detail["months"]]
    return {"month": dc.MONTHS[month - 1].lower(), "events": dc.SEASON_CALENDAR.get(month, []), "in_season": in_season}


def _radius_block():
    from core import dop_content as dc

    places = sorted((p for p in dc.GUIDE if p.get("minutes")), key=lambda p: p["minutes"])
    top = max(p["minutes"] for p in places) if places else 60
    return {"places": [{"title": p["title"], "minutes": p["minutes"], "drive": p["drive"],
                        # Строкой: локаль ru вывела бы «4,7» — CSS такое не поймёт.
                        "left": f"{4 + p['minutes'] / top * 92:.1f}"} for p in places]}


def blocks_for(key, slot="after"):
    from core.dop_pages import _image

    blocks = []
    for block in EXTRAS.get(key, []):
        if block.get("slot", "after") != slot:
            continue
        block = dict(block)
        if block["type"] == "collage":
            block["photos"] = [image for image in (_image(source) for source in block["images"]) if image]
            if not block["photos"]:
                continue
        elif block["type"] == "now":
            block.update(_now_block())
        elif block["type"] == "radius":
            block.update(_radius_block())
        blocks.append(block)
    return blocks
