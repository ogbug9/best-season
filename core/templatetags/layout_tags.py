@register.filter
def layout_lines(value, key):
    words = str(value).split()
    def comparable(items):
        return [re.sub('[«»“”"]', '', word).replace('ё', 'е') for word in items]
    for reference in LINES.get(key, []):
        if comparable(words) == comparable(reference.split()):
            lines = []
            offset = 0
            for line in reference.splitlines():
                count = len(line.split())
                lines.append(' '.join(words[offset:offset + count]))
                offset += count
            return '\n'.join(lines)
    return value


@register.filter(is_safe=True)
def layout_richtext(value, key):
    """После richtext; не трогаем абзацы со ссылками/выделениями."""
    def paragraph(match):
        content = re.sub(r'<br\s*/?>', ' ', match[2], flags=re.I)
        if '<' in content:
            return match[0]
        plain = unescape(content)
        desktop = layout_lines(plain, key + '_desktop')
        mobile = layout_lines(plain, key + '_mobile')
        if key == 'about' and ' '.join(plain.split()) in {
            ' '.join(LINES['about_mobile'][1].split()),
            ' '.join(HOME_ABOUT_MOBILE_UPDATED.split()),
        }:
            mobile = HOME_ABOUT_MOBILE_UPDATED
        # В мобильном фрейме каталога показан только первый абзац
        # стандартного вступления; авторский текст оставляем целиком.
        if key == 'intro' and mobile != plain:
            mobile = '\n'.join(mobile.splitlines()[:5])
        if desktop == plain and mobile == plain:
            return match[0]
        return match[1] + str(format_html(
            '<span class="home-desktop-copy">{}</span>'
            '<span class="home-mobile-copy">{}</span>',
            mark_safe(str(escape(desktop)).replace('\n', ' <br>')),
            mark_safe(str(escape(mobile)).replace('\n', ' <br>')),
        )) + '</p>'
    # Draftail пишет абзацы с атрибутом (<p data-block-key="...">), и
    # регексп по голому <p> не находил ни одного текста, правленного
    # в админке. Открывающий тег возвращаем как есть, spans кладём внутрь.
    return mark_safe(re.sub(r'(<p\b[^>]*>)(.*?)</p>', paragraph, str(conditional_escape(value)), flags=re.S))


