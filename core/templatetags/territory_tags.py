"""Переносы подписей мозаики по макету, без изменения названий в CMS."""

from django import template

register = template.Library()

TERRITORY_LINES = {
    "Контактная ферма": "Контактная\nферма",
    "Батут и детская площадка": "Батут и детская\nплощадка",
    "Костровая зона": "Костровая\nзона",
    "Спортивные игры": "Спортивные\nигры",
    "Русская баня": "Русская\nбаня",
    "Финская сауна": "Финская\nсауна",
    'Река "Скнижка"': 'Река\n"Скнижка"',
    "Большая беседка": "Большая\nбеседка",
    "Что вас здесь ждёт. Всё по порядку": "Что вас\nздесь ждёт.\nВсё по порядку",
}


@register.filter
def territory_lines(value):
    return TERRITORY_LINES.get(value, value)
