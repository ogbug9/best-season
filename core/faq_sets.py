def page_faq(questions):
    """Вернуть опубликованные вопросы в порядке макета, независимо от общего FAQ."""
    from core.models import FaqItem

    by_question = {
        item.question: item for item in FaqItem.objects.filter(
            is_published=True, question__in=[question for question, _ in questions]
        )
    }
    return [by_question[question] for question, _ in questions if question in by_question]
