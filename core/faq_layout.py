class AnswerParser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts = []
        self.text = ''

    def handle_starttag(self, tag, attrs):
        self.parts.append(('tag', self.get_starttag_text(), None))
        if tag in {'p', 'li', 'div', 'br'}:
            self.text += '\n'

    def handle_endtag(self, tag):
        self.parts.append(('tag', f'</{tag}>', None))
        if tag in {'p', 'li', 'div'}:
            self.text += '\n'

    def handle_data(self, data):
        self.parts.append(('data', data, len(self.text)))
        self.text += data


def format_answer(value, question):
    source = str(value)
    plan = DESKTOP_LINES.get(question)
    if not plan:
        return source
    parsed = AnswerParser()
    parsed.feed(source)
    if parsed.text.split() != plan.split():
        return source
    words = list(re.finditer(r'\S+', parsed.text))
    indices = []
    count = 0
    for line in plan.splitlines()[:-1]:
        count += len(line.split())
        if '\n' not in parsed.text[words[count - 1].end():words[count].start()]:
            indices.append(words[count].start())
    output = []
    for kind, data, offset in parsed.parts:
        if kind == 'tag':
            output.append(data)
            continue
        start = 0
        for position in indices:
            if offset <= position < offset + len(data):
                end = position - offset
                output.extend((escape(data[start:end]), '<br class="faq__reference-break">'))
                start = end
        output.append(escape(data[start:]))
    return ''.join(output)
